import { test } from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { mcpClient } from '../dev/mcp-client.mjs';

test('real MCP transport: recent 600 steps, all-time totals, family, browser and activity', async () => {
  const root = mkdtempSync(join(tmpdir(), 'glm-mcp-test-'));
  mkdirSync(join(root, 'cli/db'), { recursive: true }); mkdirSync(join(root, 'cli/rollout'));
  const db = new DatabaseSync(join(root, 'cli/db/db.sqlite'));
  db.exec(`
    CREATE TABLE session(id TEXT, title TEXT, directory TEXT, parent_id TEXT, task_type TEXT, time_created INTEGER, time_updated INTEGER, time_archived INTEGER, time_compacting INTEGER, time_deleted INTEGER);
    CREATE TABLE model_usage(id TEXT, session_id TEXT, started_at INTEGER, completed_at INTEGER, turn_id TEXT, model_id TEXT, status TEXT, query_source TEXT, input_tokens INTEGER, output_tokens INTEGER, reasoning_tokens INTEGER, cache_read_input_tokens INTEGER, cache_creation_input_tokens INTEGER, computed_total_tokens INTEGER, duration_ms INTEGER, time_to_first_token_ms INTEGER, error_type TEXT, finish_reason TEXT, attempt_index INTEGER);
    CREATE TABLE tool_usage(id TEXT, session_id TEXT, tool_call_id TEXT, tool_name TEXT, status TEXT, started_at INTEGER, duration_ms INTEGER, exit_code INTEGER, error_type TEXT, output_bytes INTEGER);
    CREATE TABLE turn_usage(session_id TEXT, started_at INTEGER, cancelled_by_user INTEGER, context_exceeded INTEGER, status TEXT, error_type TEXT);
    CREATE TABLE part(id TEXT, session_id TEXT, message_id TEXT, sequence INTEGER, time_created INTEGER, data TEXT);
    CREATE TABLE message(id TEXT, session_id TEXT, time_created INTEGER, data TEXT);
    CREATE TABLE todo(session_id TEXT, content TEXT, status TEXT, priority TEXT, position INTEGER, time_created INTEGER, time_updated INTEGER);
  `);
  const now = Date.now();
  const insertSession = db.prepare('INSERT INTO session VALUES(?,?,?,?,?,?,?,?,?,?)');
  insertSession.run('sess_root', 'Root', '/workspace/a', null, null, now - 3600000, now, null, null, null);
  insertSession.run('sess_child', 'Child', '/workspace/a', 'sess_root', null, now - 10000, now, null, null, null);
  const insertStep = db.prepare('INSERT INTO model_usage VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)');
  for (let i = 0; i < 605; i++) insertStep.run(`step_${String(i).padStart(4, '0')}`, 'sess_root', now - (605 - i) * 1000, now, 'turn', 'glm-5', 'completed', 'chat', 100 + i, 10, 0, 50, 0, 110 + i, 1000, 100, null, 'stop', 0);
  db.prepare('INSERT INTO tool_usage VALUES(?,?,?,?,?,?,?,?,?,?)').run('tool1', 'sess_root', 'call1', 'bash', 'error', now, 6000, 1, 'process_exit', 100);
  db.prepare('INSERT INTO part VALUES(?,?,?,?,?,?)').run('p1', 'sess_root', 'm1', 0, now, JSON.stringify({ type: 'tool', callID: 'call1', tool: 'bash', state: { input: { command: 'node --test', run_in_background: true }, status: 'error' } }));
  for (let i = 0; i < 13; i++) {
    db.prepare('INSERT INTO tool_usage VALUES(?,?,?,?,?,?,?,?,?,?)').run(`extra${i}`, 'sess_root', `extra${i}`, 'bash', 'completed', now - i - 1, 10, 0, null, 0);
    db.prepare('INSERT INTO part VALUES(?,?,?,?,?,?)').run(`p_extra${i}`, 'sess_root', 'm1', i + 1, now, JSON.stringify({ type: 'tool', callID: `extra${i}`, tool: 'bash', state: { input: { command: `program${i} --help` }, status: 'completed' } }));
  }
  const io = { request: { body: { model: 'glm-5', messages: [{ role: 'user', content: 'Test context' }] } }, response: { usage: { prompt_tokens: 100, completion_tokens: 10 } }, completedAt: new Date(now).toISOString() };
  writeFileSync(join(root, 'cli/rollout/model-io-sess_root.jsonl'), JSON.stringify(io) + '\n');
  const insertTodo = db.prepare('INSERT INTO todo VALUES(?,?,?,?,?,?,?)');
  insertTodo.run('sess_root', '实现费用轴', 'in_progress', 'high', 0, now - 5000, now - 1000);
  insertTodo.run('sess_root', '补充测试', 'completed', 'medium', 1, now - 8000, now - 2000);
  insertTodo.run('sess_child', '验收清单', 'pending', 'low', 0, now - 4000, now - 3000);
  insertSession.run('sess_subagent_agent_12345678-1234-5678-9abc-def012345678', '你在 zcode-plugins 仓库实现功能', '/workspace/a', 'sess_child', null, now - 6000, now - 1000, null, null, null);
  db.prepare('INSERT INTO part VALUES(?,?,?,?,?,?)').run('p_agent1', 'sess_child', 'm2', 0, now - 6000, JSON.stringify({ type: 'tool', callID: 'call_agent1', tool: 'Agent', state: { status: 'completed', input: { description: '实现功能', prompt: '你在 zcode-plugins 仓库实现功能' }, output: 'Async agent launched successfully.\nagentId: agent_12345678-1234-5678-9abc-def012345678 (internal ID)' } }));
  db.close();
  const client = mcpClient({ GLM_ZCODE_DIR: root, GLM_USAGE_DATA_DIR: join(root, 'config') });
  try {
    const init = await client.request('initialize'); assert.equal(init.serverInfo.name, 'glm-usage'); assert.equal(init.serverInfo.icons.length, 2);
    const context = await client.call('get_session_context', { session_id: 'sess_root' });
    assert.equal(context.steps.length, 600); assert.equal(context.session.steps, 605); assert.equal(context.steps_offset, 5);
    assert.equal(context.steps[0].id, 'step_0005'); assert.equal(context.steps.at(-1).id, 'step_0604');
    assert.equal(context.session.token_sums.input, 605 * 100 + 604 * 605 / 2);
    assert.equal(context.stats.commands.length, 12); assert.equal(context.stats.command_calls, 14);
    const fleet = await client.call('get_fleet', { session_id: 'sess_child' });
    assert.equal(fleet.lead.id, 'sess_root'); assert.equal(fleet.summary.running, 3); assert.equal(fleet.lead.context, 704);
    assert.equal(fleet.members.length, 2);
    assert.equal(fleet.summary.agents, 3);
    assert.equal(fleet.comms.length, 1);
    assert.equal(fleet.comms[0].from, 'sess_child');
    assert.equal(fleet.comms[0].to, 'sess_subagent_agent_12345678-1234-5678-9abc-def012345678');
    assert.equal(fleet.comms[0].kind, 'delegate'); assert.equal(fleet.comms[0].description, '实现功能');
    assert.equal(fleet.works.length, 3);
    assert.equal(fleet.works.filter(w => w.status === 'in_progress').length, 1);
    assert.equal(fleet.works.filter(w => w.status === 'pending').length, 1);
    assert.equal(fleet.works.filter(w => w.status === 'completed').length, 1);
    const browser = await client.call('get_context_browser', { session_id: 'sess_root' });
    assert.equal(browser.total, 100); assert.equal(browser.has_previous, false);
    await assert.rejects(client.call('get_context_browser', { session_id: 'sess_root', prev: true }), /上一条/);
    const item = browser.cats.find(c => c.key === 'user_messages').items[0];
    const detail = await client.call('get_context_item', { session_id: 'sess_root', item_id: item.id });
    assert.equal(detail.content, 'Test context');
    await assert.rejects(client.call('get_context_item', { session_id: '../escape', item_id: item.id }), /无效/);
    await assert.rejects(client.call('get_context_item', { session_id: 'sess_root', item_id: 'stale' }), /更新/);
    const activity = await client.call('get_activity', { session_id: 'sess_root', kind: 'commands' });
    assert.equal(activity.rows.length, 14); assert.equal(activity.rows[0].program, 'node'); assert(activity.rows[0].background);
    const insights = await client.call('get_insights', { range: '7d' });
    assert.equal(insights.kpis.steps, 605); assert.equal(insights.sessions[0].context, 704);
    assert.equal(!('session_ids' in insights.daily[0]), true);
    assert.equal(!('session_ids' in insights.heatmap[0]), true);
    assert.equal(insights.daily7.at(-1).day, insights.daily.at(-1).day);
    assert.equal(insights.daily7.length, insights.daily.length);
    const daySessions = await client.call('get_day_sessions', { day: new Date(now).toLocaleDateString('en-CA') });
    assert(daySessions.session_ids.includes('sess_root'));
    assert.deepEqual(await client.call('get_day_sessions', { day: '2000-01-01' }), { day: '2000-01-01', session_ids: [] });
    await assert.rejects(client.call('get_day_sessions', { day: 'not-a-day' }), /YYYY-MM-DD/);
    // 缓存价计入费用估算：cache_read 共 30250 tokens，按缓存价 2 计（旧口径按输入价 8 会得 2.1151）
    await client.call('set_prices', { prices: { 'GLM-5': [8, 28, 2] } });
    const insightsPriced = await client.call('get_insights', { range: '7d' });
    assert.equal(insightsPriced.kpis.cost, 1.9336);
    // 刷新频率：0 = 暂停（手动刷新不受影响），常规区间照常，越界拒绝
    const setRefresh = (seconds) => client.request('tools/call', { name: 'set_refresh', arguments: { seconds } }).then(r => r.content[0].text);
    assert.match(await setRefresh(0), /暂停自动刷新/);
    assert.match(await setRefresh(45), /45 秒/);
    await assert.rejects(() => setRefresh(1), /3~600/);
    // 新增一次隔日活动和一次同名失败调用，模拟面板真实工具入口。
    const extra = new DatabaseSync(join(root,'cli/db/db.sqlite'));
    const yesterday = new Date(now); yesterday.setDate(yesterday.getDate()-1); yesterday.setHours(12,0,0,0);
    const past = +yesterday, selectedDay=yesterday.toLocaleDateString('en-CA');
    extra.prepare('INSERT INTO model_usage VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)').run('old-step','sess_root',past,past+100,'historic-turn','other-model','completed','chat',300,40,0,0,0,340,100,10,null,'stop',0);
    const tool = extra.prepare('INSERT INTO tool_usage VALUES(?,?,?,?,?,?,?,?,?,?)');
    const part = extra.prepare('INSERT INTO part VALUES(?,?,?,?,?,?)');
    tool.run('past-file','sess_root','past-call','Read','error',past,5,1,'denied',18);
    part.run('receipt','sess_root','pmsg',0,past,JSON.stringify({type:'tool',tool:'Read',callID:'past-call',state:{input:{file_path:'src/past.js',command:'git show'},error:'fixture access denied'}}));
    for(let i=0;i<506;i++) tool.run('noise-'+i,'sess_root','noise-call-'+i,'Read','completed',now,5,0,null,0);
    extra.close();
    const dayView = await client.call('get_insights',{range:'today',day:selectedDay});
    assert.equal(dayView.kpis.steps,1); assert.equal(dayView.sessions[0].steps,1);
    assert.equal(dayView.tools[0].name,'Read'); assert.deepEqual(dayView.commands,[{program:'git',count:1}]);
    assert.deepEqual((await client.call('get_activity',{kind:'commands',day:new Date(now).toLocaleDateString('en-CA'),pick:'git'})).session_ids,[]);
    assert.deepEqual((await client.call('get_activity',{kind:'commands',day:selectedDay,pick:'git'})).session_ids,['sess_root']);
    assert.equal((await client.call('get_activity',{kind:'files',session_id:'sess_root'})).rows[0].id,'past-file');
    const firstPage = await client.call('get_activity',{kind:'tools',session_id:'sess_root'});
    const nextPage = await client.call('get_activity',{kind:'tools',session_id:'sess_root',cursor:firstPage.cursor});
    assert.equal(new Set([...firstPage.rows,...nextPage.rows].map(r=>r.id)).size,521);
    assert.equal((await client.call('get_activity_detail',{session_id:'sess_root',record_id:'past-file'})).output,'fixture access denied');
    assert.equal((await client.call('get_activity_detail',{session_id:'sess_root',record_id:'noise-0'})).matched,false);
    await assert.rejects(client.call('get_activity_detail',{session_id:'sess_child',record_id:'past-file'}),/不可用/);
    const mixed = (await client.call('get_session_context',{session_id:'sess_root'})).session;
    assert.equal(mixed.cost,null);assert.equal(mixed.priced_models,1);assert.equal(mixed.total_models,2);assert.equal(mixed.window_source,'内置');
    const fleetMixed = (await client.call('get_fleet',{session_id:'sess_root'})).lead;
    assert.equal(fleetMixed.cost,null);assert.equal(fleetMixed.priced_models,1);
    await client.call('set_prices',{prices:{'other-model':[100,200]}});
    const priced = (await client.call('get_session_context',{session_id:'sess_root'})).session;
    assert(Math.abs(priced.cost-(1.9336+.038))<0.00001);
    const logFile=join(root,'cli/rollout/model-io-sess_root.jsonl');
    const historic={...io,turnId:'historic-turn',requestId:'old-step',startedAt:yesterday.toISOString()};
    writeFileSync(logFile,[historic,io].map(x=>JSON.stringify(x)).join('\n')+'\n');
    const selected=await client.call('get_context_browser',{session_id:'sess_root',step_id:'old-step'});
    assert.equal(selected.match,'exact');assert(selected.snapshot_key);
    const comparison=await client.call('get_context_browser',{session_id:'sess_root',compare:true});assert.equal(comparison.comparison.categories.length,7);
    const content=await client.call('get_context_item',{session_id:'sess_root',snapshot_key:selected.snapshot_key,item_id:item.id});assert.equal(content.content,'Test context');
    assert.equal((await client.call('get_context_browser',{session_id:'sess_root',step_id:'step_0604'})).match,'missing');
    const resource = await client.request('resources/read', { uri: 'ui://glm-usage/panel.html' });
    assert(!resource.contents[0].text.includes('@inline:'));
  } finally { client.close(); rmSync(root, { recursive: true, force: true }); }
});
